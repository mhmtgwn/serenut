import 'dart:convert';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:serenutos/domain/services/barcode_standard.dart';
import 'package:serenutos/domain/services/dataset_import_service.dart';
import 'package:serenutos/domain/repositories/base_repository.dart';
import 'package:serenutos/infrastructure/services/cart_persistence_service.dart';
import 'package:serenutos/infrastructure/services/financial_integrity_service.dart';

class _MockCell {
  final dynamic value;
  const _MockCell(this.value);
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  group('Category F1: Barcode Normalization & Excel Artifact Stripping', () {
    test('normalizes barcode by stripping trailing .0 generated by Excel numeric cells', () {
      expect(BarcodeStandard.normalize('8690504090106.0'), '8690504090106');
      expect(BarcodeStandard.normalize('8690504090106'), '8690504090106');
      expect(BarcodeStandard.normalize('0123456789012.0'), '123456789012');
    });

    test('preserves alphanumeric barcodes without numeric .0 suffix', () {
      expect(BarcodeStandard.normalize('ITEM.01'), 'ITEM.01');
      expect(BarcodeStandard.normalize('ABC.0'), 'ABC.0');
    });

    test('DatasetImportService._staticParseBarcode strips .0 and expands scientific exponent', () {
      expect(DatasetImportService.parseBarcodeForTesting(const _MockCell(8690504090106.0)), '8690504090106');
      expect(DatasetImportService.parseBarcodeForTesting(const _MockCell('8690504090106.0')), '8690504090106');
      expect(DatasetImportService.parseBarcodeForTesting(const _MockCell('8.690504090106e+12')), '8690504090106');
      expect(DatasetImportService.parseBarcodeForTesting(const _MockCell(8690504090106)), '8690504090106');
    });
  });

  group('Category F2: Turkish Currency & Comma Decimal Price Parsing', () {
    test('accurately parses localized Turkish currency strings without zeroing out prices', () {
      expect(DatasetImportService.parseDoubleForTesting(const _MockCell('125,50')), 125.5);
      expect(DatasetImportService.parseDoubleForTesting(const _MockCell('125,50 TL')), 125.5);
      expect(DatasetImportService.parseDoubleForTesting(const _MockCell('₺ 125,50')), 125.5);
      expect(DatasetImportService.parseDoubleForTesting(const _MockCell('₺ 1.250,50')), 1250.5);
      expect(DatasetImportService.parseDoubleForTesting(const _MockCell('1.250,50 TL')), 1250.5);
      expect(DatasetImportService.parseDoubleForTesting(const _MockCell('1,250.50')), 1250.5);
      expect(DatasetImportService.parseDoubleForTesting(const _MockCell(125.5)), 125.5);
      expect(DatasetImportService.parseDoubleForTesting(const _MockCell('0')), 0.0);
      expect(DatasetImportService.parseDoubleForTesting(const _MockCell('')), 0.0);
      expect(DatasetImportService.parseDoubleForTesting(null), 0.0);
    });
  });

  group('Category F3: VAT Rate Parsing & Turkish Header Recognition', () {
    test('strictly preserves genuine 0% VAT rate and defaults empty to standard 20%', () {
      expect(DatasetImportService.parseVatForTesting(const _MockCell(0)), 0);
      expect(DatasetImportService.parseVatForTesting(const _MockCell('0')), 0);
      expect(DatasetImportService.parseVatForTesting(const _MockCell('0%')), 0);
      expect(DatasetImportService.parseVatForTesting(const _MockCell('%0')), 0);
      expect(DatasetImportService.parseVatForTesting(const _MockCell('KDV 0')), 0);
      expect(DatasetImportService.parseVatForTesting(const _MockCell(null)), 20);
      expect(DatasetImportService.parseVatForTesting(const _MockCell('')), 20);
      expect(DatasetImportService.parseVatForTesting(null), 20);
      expect(DatasetImportService.parseVatForTesting(const _MockCell(10)), 10);
      expect(DatasetImportService.parseVatForTesting(const _MockCell('%10')), 10);
      expect(DatasetImportService.parseVatForTesting(const _MockCell(20)), 20);
    });

    test('recognizes standard and colloquial Turkish column headers', () {
      final header = [
        const _MockCell('Barkodu'),
        const _MockCell('Ürün Adı'),
        const _MockCell('Birim Fiyatı'),
        const _MockCell('KDV (%)'),
        const _MockCell('Stok Adeti'),
      ];
      final cols = DatasetImportService.resolveColumnsForTesting(header);
      expect(cols['barcode'], 0);
      expect(cols['name'], 1);
      expect(cols['price'], 2);
      expect(cols['vat'], 3);
      expect(cols['quantity'], 4);
    });
  });

  group('Category F4: Phone Suffix Matching for SMS Reminder Logs', () {
    test('extracts trailing 10 significant digits across international and local formats', () {
      String extractSuffix(String phone) {
        final clean = phone.replaceAll(RegExp(r'[^0-9]'), '');
        return clean.length >= 10 ? clean.substring(clean.length - 10) : clean;
      }

      const expected = '5551234567';
      expect(extractSuffix('+905551234567'), expected);
      expect(extractSuffix('905551234567'), expected);
      expect(extractSuffix('05551234567'), expected);
      expect(extractSuffix('0 (555) 123 45 67'), expected);
      expect(extractSuffix('5551234567'), expected);
    });
  });

  group('Category F6: Cart Persistence Service Type-Safety on Load', () {
    setUp(() {
      SharedPreferences.setMockInitialValues({});
    });

    test('recovers safely when cart quantities contain double or num values', () async {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(
        'serenut_cart_quantities',
        jsonEncode({'prod1': 2.0, 'prod2': 5, 'prod3': '3'}),
      );
      await prefs.setString(
        'serenut_cart_products',
        jsonEncode({
          'prod1': {
            'id': 'prod1',
            'name': 'Ürün 1',
            'price': 10.5,
            'quantity': 10,
            'category': 'Genel',
          },
          'prod2': {
            'id': 'prod2',
            'name': 'Ürün 2',
            'price': 20.0,
            'quantity': 5,
            'category': 'Gıda',
          },
        }),
      );

      final service = CartPersistenceService(prefs);
      final loaded = service.loadCart();

      final quantities = loaded['cartQuantities'] as Map<String, int>;
      expect(quantities['prod1'], 2);
      expect(quantities['prod2'], 5);
      expect(quantities['prod3'], 3);

      final products = loaded['cartProducts'] as Map<String, ProductEntity>;
      expect(products.containsKey('prod1'), isTrue);
      expect(products['prod1']!.name, 'Ürün 1');
      expect(products['prod1']!.price, 10.5);
    });

    test('handles corrupted customer or quantities without crashing', () async {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString('serenut_cart_customer', '{invalid_json}');
      await prefs.setString('serenut_cart_quantities', 'not_a_json_map');

      final service = CartPersistenceService(prefs);
      final loaded = service.loadCart();

      expect(loaded['cartQuantities'], isEmpty);
      expect(loaded['selectedCustomer'], isNull);
    });
  });

  group('Category F8: Operation Queue & SyncOperation Resilience', () {
    setUp(() {
      SharedPreferences.setMockInitialValues({});
    });

    test('SyncOperation.fromMap safely deserializes dynamic maps and num retry counts', () {
      final rawMap = <dynamic, dynamic>{
        'id': 'op-123',
        'type': 'create_sale',
        'payload': <dynamic, dynamic>{
          'sale_id': 's-1',
          'total': 150.75,
        },
        'idempotencyKey': 'idemp-xyz',
        'retryCount': 3.0,
      };

      final op = SyncOperation.fromMap(Map<String, dynamic>.from(rawMap));
      expect(op.id, 'op-123');
      expect(op.type, 'create_sale');
      expect(op.payload['sale_id'], 's-1');
      expect(op.payload['total'], 150.75);
      expect(op.idempotencyKey, 'idemp-xyz');
      expect(op.retryCount, 3);
    });

    test('OperationQueueService.getQueue skips corrupted entries and returns valid ones', () async {
      final prefs = await SharedPreferences.getInstance();
      final validOp = SyncOperation(
        id: 'valid-1',
        type: 'refund',
        payload: {'amount': 50},
        idempotencyKey: 'idemp-1',
      );
      await prefs.setStringList('serenut_sync_queue', [
        jsonEncode(validOp.toMap()),
        'corrupted-entry-{{{',
        jsonEncode({'id': 'valid-2', 'type': 'sale', 'payload': {}, 'idempotencyKey': 'k2'}),
      ]);

      final queueService = OperationQueueService(prefs);
      final queue = queueService.getQueue();

      expect(queue.length, 2);
      expect(queue[0].id, 'valid-1');
      expect(queue[1].id, 'valid-2');
    });
  });
}
